"""Generate README.md and per-topic paper lists (docs/papers/*.md)."""

from __future__ import annotations

import logging
import re
from datetime import datetime
from pathlib import Path
from typing import Any

from . import config, translator
from .categorizer import get_statistics, group_by_category
from .summarizer import short_authors

logger = logging.getLogger(__name__)

GENERATED_MARKER = "<!-- Generated by 3DGenomeHub (src/genome_literature/readme_generator.py). Do not edit by hand. -->"
ML_PAGE_SLUG = "ai-ml-3d-genome"
LATEST_ML_ROWS = 20
LATEST_OTHER_ROWS = 10
TOP_CITED_ROWS = 20


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def github_anchor(heading: str) -> str:
    """Anchor GitHub generates for a heading."""
    s = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return s.replace(" ", "-")


def md_escape(text: str) -> str:
    return re.sub(r"([\\`*_\[\]<>|])", r"\\\1", text or "").replace("\n", " ")


def badge(label: str, message: Any, color: str) -> str:
    def enc(s: Any) -> str:
        return str(s).replace("-", "--").replace("_", "__").replace(" ", "%20").replace("/", "%2F")
    return f"![{label}](https://img.shields.io/badge/{enc(label)}-{enc(message)}-{color})"


def paper_links(p: dict[str, Any]) -> str:
    links = []
    if p.get("doi"):
        links.append(f"[DOI](https://doi.org/{p['doi']})")
    if p.get("pmid"):
        links.append(f"[PubMed](https://pubmed.ncbi.nlm.nih.gov/{p['pmid']}/)")
    if p.get("arxiv_id"):
        links.append(f"[arXiv](https://arxiv.org/abs/{p['arxiv_id']})")
    if p.get("pdf_url"):
        links.append(f"[PDF]({p['pdf_url']})")
    if not links and p.get("url"):
        links.append(f"[Link]({p['url']})")
    return " · ".join(links)


def tags(p: dict[str, Any], with_track: bool = True) -> str:
    items = []
    if with_track and p.get("track") == "ml":
        items.append("`AI/ML`")
    items += [f"`{m}`" for m in (p.get("dl_methods") or [])[:3]]
    if p.get("is_preprint"):
        items.append("`preprint`")
    return " ".join(items)


def title_link(p: dict[str, Any]) -> str:
    title = md_escape(p.get("title", ""))
    return f"[{title}]({p['url']})" if p.get("url") else title


_MD_BREAK = "  \n  "


def zh_title(p: dict[str, Any], sep: str = "<br>") -> str:
    """Chinese title line when an academic translation is available."""
    return f"{sep}{md_escape(p['title_zh'])}" if p.get("title_zh") else ""


def category_link(cat: str, prefix: str = "docs/papers/") -> str:
    return f"[{md_escape(cat)}]({prefix}{slugify(cat)}.md)"


