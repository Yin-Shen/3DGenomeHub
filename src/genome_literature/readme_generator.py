def _entry(p: dict[str, Any]) -> str:
    authors = md_escape(short_authors(p.get("authors") or [], limit=3))
    venue = md_escape(p.get("journal") or "")
    cites = f" · {p['citations']} citations" if p.get("citations") else ""
    t = tags(p)
    links = paper_links(p)
    zh = zh_title(p, _MD_BREAK)
    return (
        f"- **{title_link(p)}**{zh}  \n  {authors}. *{venue}* ({p.get('date') or p.get('year') or 'n.d.'}){cites}"
        f"{'  ' + t if t else ''}{'  · ' + links if links else ''}"
    )


def paper_list_page(title: str, description: str, papers: list[dict[str, Any]]) -> str:
    date = datetime.now().strftime("%Y-%m-%d")
    ml = sum(1 for p in papers if p.get("track") == "ml")
    lines = [
        GENERATED_MARKER,
        f"# {md_escape(title)}",
        "",
        f"> {md_escape(description)}" if description else "",
        "",
        f"[← Back to overview](../../README.md) · **{len(papers)}** papers · **{ml}** AI/ML · updated {date}",
    ]
    by_year: dict[Any, list[dict[str, Any]]] = {}
    for p in sorted(papers, key=lambda x: (x.get("date") or "", x.get("relevance", 0)), reverse=True):
        by_year.setdefault(p.get("year") or "Undated", []).append(p)
    lines.append("")
    lines.append(" · ".join(f"[{y}](#{github_anchor(str(y))})" for y in by_year))
    for y, items in by_year.items():
        lines += ["", f"## {y}", ""]
        lines += [_entry(p) for p in items]
    return "\n".join(line for line in lines if line is not None) + "\n"


def write_outputs(papers: list[dict[str, Any]], new_papers: list[dict[str, Any]] | None = None) -> list[Path]:
    """Write README.md and docs/papers/*.md; remove stale generated pages."""
    written: list[Path] = []
    cache = translator.load_cache()
    papers = translator.attach_translations(papers, cache)
    new_papers = translator.attach_translations(new_papers or [], cache)
    config.README_PATH.write_text(generate_readme(papers, new_papers), encoding="utf-8")
    written.append(config.README_PATH)

    out_dir = config.CATEGORY_PAGES_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    keep: set[Path] = set()
    if papers:
        ml = [p for p in papers if p.get("track") == "ml"]
        path = out_dir / f"{ML_PAGE_SLUG}.md"
        path.write_text(paper_list_page(
            "AI / ML × 3D Genome",
            "All papers applying deep learning or machine learning to 3D genome data.", ml), encoding="utf-8")
        keep.add(path)
        for cat, items in group_by_category(papers).items():
            path = out_dir / f"{slugify(cat)}.md"
            desc = config.CATEGORIES.get(cat, {}).get("description", "")
            path.write_text(paper_list_page(cat, desc, items), encoding="utf-8")
            keep.add(path)
    for path in out_dir.glob("*.md"):
        if path not in keep and path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            path.unlink()
    written.extend(sorted(keep))
    logger.info("Wrote README.md and %d topic pages", len(keep))
    return written
